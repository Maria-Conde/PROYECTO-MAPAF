export const INITIAL_SPECTRAL: SpectralPoint[] = Array.from({ length: 48 }, (_, i) => {
  const freq = (i + 1) * 5; // 5Hz to 240Hz
  let amplitude = 0.4 + Math.sin(freq * 0.1) * 0.15;
  if (freq >= 55 && freq <= 65) {
    amplitude += 2.8 * (1 - Math.abs(freq - 60) / 10);
  }
  if (freq >= 115 && freq <= 125) {
    amplitude += 3.9 * (1 - Math.abs(freq - 120) / 10);
  }
  if (freq >= 175 && freq <= 185) {
    amplitude += 1.4 * (1 - Math.abs(freq - 180) / 10);
  }
  return {
    frequency: freq,
    amplitude: Number(amplitude.toFixed(2)),
    baseline: Number((0.6 + (freq === 60 ? 2.1 : freq === 120 ? 1.5 : 0.1)).toFixed(2)),
  };
});

